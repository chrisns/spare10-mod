/**
 * codex/bin/broker.sh with its fixed places moved under `dir`, so the case does not depend on the Node.js
 * installs of this machine. `nodes` maps a place (a PATH folder, a fixed place or an nvm version) to a
 * script, or to 'real' for this Node.js.
 */
function movedBroker(dir: string, nodes: Record<string, 'old' | 'real'>): string {
  const fixed = ['/opt/homebrew/bin/node', '/usr/local/bin/node', '/usr/bin/node']
  let sh = read('codex/bin/broker.sh')
  for (const f of fixed) {
    assert.ok(sh.includes(` ${f}`), `broker.sh names ${f}`)
    sh = sh.replace(` ${f}`, ` ${join(dir, 'fixed', f)}`)
  }
  for (const [place, kind] of Object.entries(nodes)) {
    const file = place.startsWith('/') ? join(dir, 'fixed', place) : join(dir, place)
    mkdirSync(dirname(file), { recursive: true })
    if (kind === 'real') symlinkSync(process.execPath, file)
    else {
      // An old Node.js: it fails the version check of broker.sh.
      writeFileSync(file, '#!/bin/sh\nexit 1\n')
      chmodSync(file, 0o755)
    }
  }
  const out = join(dir, 'broker.sh')
  writeFileSync(out, sh)
  return out
}

test('bundle: with no Node.js 20 or later, broker.sh prints the stderr line and exits 1', async (t) => {
  const w = world(t)
  const home = join(w.dir, 'home')
  const script = movedBroker(w.dir, { 'path/node': 'old', '/opt/homebrew/bin/node': 'old', 'home/.nvm/versions/node/v18.20.4/bin/node': 'old' })
  // PATH holds no tools: broker.sh takes them from /usr/bin and /bin.
  const r = await run(t, '/bin/sh', [script], { ...w.env, HOME: home, PATH: join(w.dir, 'path') })
  assert.equal(r.code, 1)
  assert.equal(r.stdout, '')
  assert.equal(r.stderr, 'spare10: no Node.js 20 or later found. Install Node.js, or switch off the spare10 plugin in ~/.codex/config.toml.\n')
})

