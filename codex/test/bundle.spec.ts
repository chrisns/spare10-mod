test('bundle: broker.sh takes a fixed Node.js before the one on PATH, and runs no node, tool or ps from PATH', async (t) => {
  // Codex runs broker.sh outside its sandbox, and the agent can write a PATH folder such as the .venv/bin of a project.
  const w = world(t)
  const script = movedBroker(w.dir, { '/opt/homebrew/bin/node': 'real' })
  const venv = join(w.dir, 'venv')
  const marks = join(w.dir, 'marks')
  mkdirSync(venv)
  mkdirSync(marks)
  for (const tool of ['node', 'ls', 'sed', 'sort', 'cut', 'ps']) {
    const real = tool === 'node' ? process.execPath : [`/bin/${tool}`, `/usr/bin/${tool}`].find((f) => existsSync(f))
    assert.ok(real !== undefined, `${tool} exists`)
    // Each stand-in leaves a mark, then runs the real tool, so the broker still works when one runs.
    writeFileSync(join(venv, tool), `#!/bin/sh\n: > '${join(marks, tool)}'\nexec '${real}' "$@"\n`)
    chmodSync(join(venv, tool), 0o755)
  }
  const gate = { site: 'prompt', session: 's1', turn: 't1', transcript: null, mode: 'default', model: 'm', cwd: w.dir, prompt: 'spare10 help' }
  const r = await run(t, '/bin/sh', [script], { ...w.env, PATH: `${venv}:/usr/bin:/bin` }, {
    input: rpc(
      { jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 't', version: '0' } } },
      { jsonrpc: '2.0', method: 'notifications/initialized' },
      { jsonrpc: '2.0', id: 2, method: 'tools/call', params: { name: 'gate', arguments: gate, _meta: { threadId: 's1' } } },
    ),
    waitFor: /"id":2/,
  })
  assert.equal(r.code, 0, r.stderr)
  assert.match(r.stdout, /"serverInfo":\{"name":"spare10","version":"[^"]+"\}/)
  assert.match(r.stdout, /"id":2,"result":\{"content"/)
  assert.deepEqual(readdirSync(marks), [], 'no stand-in on PATH ran')
})

/** A node stand-in at `file`: it runs the sh line `pre`, then this Node.js. */
function standIn(file: string, pre: string): void {
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, `#!/bin/sh\n${pre}\nexec '${process.execPath}' "$@"\n`)
  chmodSync(file, 0o755)
}

test('bundle: broker.sh takes the Node.js on PATH last, and its version probe gets no stdin and no stdout', async (t) => {
  const w = world(t)
  const home = join(w.dir, 'home')
  const script = movedBroker(w.dir, {
    '/opt/homebrew/bin/node': 'old',
    '/usr/local/bin/node': 'old',
    '/usr/bin/node': 'old',
    'home/.volta/bin/node': 'old',
    'home/.nvm/versions/node/v18.20.4/bin/node': 'old',
    'home/.local/share/mise/installs/node/18.20.4/bin/node': 'old',
  })
  // On the probe (-e), the stand-in writes to stdout and reads a line of stdin. With the MCP stream as its
  // stdin and stdout, it takes the initialize line and puts junk in front of the answers.
  const bin = join(w.dir, 'pathbin')
  standIn(join(bin, 'node'), `if [ "$1" = -e ]; then echo 'junk from the probe'; IFS= read -r line; fi`)
  const r = await run(t, '/bin/sh', [script], { ...w.env, HOME: home, PATH: bin }, {
    input: rpc(
      { jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 't', version: '0' } } },
      { jsonrpc: '2.0', id: 2, method: 'tools/list', params: {} },
    ),
    waitFor: /"id":2/,
    limitMs: 5_000,
  })
  assert.equal(r.code, 0, r.stderr)
  const replies = r.stdout.trim().split('\n').map((l) => JSON.parse(l) as { id?: number; result?: { serverInfo?: unknown } })
  assert.deepEqual(replies.find((m) => m.id === 1)?.result?.serverInfo, { name: 'spare10', version: VERSION })
})

test('bundle: broker.sh runs no Node.js from a relative PATH folder or a relative HOME', async (t) => {
  const w = world(t)
  const script = movedBroker(w.dir, {})
  const marks = join(w.dir, 'marks')
  mkdirSync(marks)
  // Both are relative to the plugin root, the cwd of broker.sh. bash makes a node in a relative PATH folder absolute.
  const rel = join(w.dir, 'rel')
  const relHome = join(w.dir, 'relhome')
  standIn(join(rel, 'node'), `: > '${join(marks, 'path')}'`)
  standIn(join(relHome, '.volta', 'bin', 'node'), `: > '${join(marks, 'volta')}'`)
  standIn(join(relHome, '.nvm', 'versions', 'node', 'v22.19.0', 'bin', 'node'), `: > '${join(marks, 'nvm')}'`)
  const r = await run(t, '/bin/sh', [script], { ...w.env, HOME: relative(ROOT, relHome), PATH: relative(ROOT, rel) })
  assert.deepEqual(readdirSync(marks), [], 'no relative node ran')
  assert.equal(r.code, 1)
  assert.equal(r.stdout, '')
  assert.equal(r.stderr, 'spare10: no Node.js 20 or later found. Install Node.js, or switch off the spare10 plugin in ~/.codex/config.toml.\n')
})
